test('menu: the 13 languages by their own name, the current one marked, in its language', function()
	local l = load({['hikari-language'] = 'es'})
	local data = l.menu_data()
	eq(data.type, 'hikari-language'); eq(data.title, 'Idioma'); eq(data.keep_open, true)
	eq(#data.items, 13, 'items')
	eq(data.items[1].title, 'English'); eq(data.items[2].title, 'Español'); eq(data.items[13].title, '简体中文')
	for i, item in ipairs(data.items) do
		eq(item.active, CODES[i] == 'es', CODES[i] .. ' active')
		eq(item.value[4], CODES[i], 'value')
		eq(item.value[1], 'script-message-to'); eq(item.value[2], SCRIPT_NAME); eq(item.value[3], 'select-language')
	end
	eq(data.items[2].hint, 'actual')
	l.open_menu()
	eq(#sent('open-menu'), 1, 'open-menu sent')
	assert(mock.bindings['open-menu'], 'binding')
end)

test('tooltips: the shipped controls get hikari tooltips in the language, the rest stays', function()
	local l = load({['hikari-language'] = 'en'})
	local controls = shipped_controls()
	eq(l.localize_controls(controls, 'en'), controls, 'English: the shipped text')
	local es = l.localize_controls(controls, 'es')
	for _, text in ipairs({'hikari_subs/open-menu?Subtítulos', 'hikari_upscale/open-menu?Escalado',
		'hikari_speed/open-menu?Velocidad', 'hikari_palettes/open-menu?Paletas',
		'hikari_update/open-menu?Actualizar hikari'}) do
		assert(es:find(text, 1, true), text)
	end
	eq(es:gsub('%?[^,]*', ''), controls:gsub('%?[^,]*', ''), 'only tooltips change')
	eq(l.localize_controls(es, 'es'), es, 'idempotent')
	eq(l.localize_controls(es, 'en'), controls, 'and back')
	local zh = l.localize_controls(controls, 'zh-hans')
	assert(zh:find('hikari_speed/open-menu?播放速度', 1, true), 'UTF-8 tooltips')
	eq(l.localize_controls(zh, 'en'), controls, 'back from Chinese')
end)

test('tooltips: conditions, badges, spaces, other buttons and a trailing comma', function()
	local l = load()
	local cases = {
		{'<has_many_audio,video>command:speed:script-binding hikari_speed/open-menu?Old',
			'<has_many_audio,video>command:speed:script-binding hikari_speed/open-menu?Velocidad'},
		{'command:speed:script-binding hikari_speed/open-menu', 'command:speed:script-binding hikari_speed/open-menu?Velocidad'},
		{'command : speed : script-binding hikari_speed/open-menu ? Old ? more',
			'command : speed : script-binding hikari_speed/open-menu?Velocidad'},
		{'command:palette:script-binding hikari_palettes/open-menu#sub>0?x', 'command:palette:script-binding hikari_palettes/open-menu#sub>0?Paletas'},
		{'command:star:script-binding other/open-menu?Mine', 'command:star:script-binding other/open-menu?Mine'},
		{'command:star:script-binding hikari_speed/open-menu-not?Mine', 'command:star:script-binding hikari_speed/open-menu-not?Mine'},
		{'cycle:repeat:loop-file:no/inf!?Bucle,menu,', 'cycle:repeat:loop-file:no/inf!?Bucle,menu,'},
		{'menu,gap,<video>command:speed:script-binding hikari_speed/open-menu?Speed,fullscreen,',
			'menu,gap,<video>command:speed:script-binding hikari_speed/open-menu?Velocidad,fullscreen,'},
		{'', ''},
	}
	for _, case in ipairs(cases) do eq(l.localize_controls(case[1], 'es'), case[2], case[1]) end
	-- A tooltip text with separators in it loses them.
	l.i18n.STRINGS.tooltip_speed.es = 'Velo, cidad?'
	eq(l.localize_config('command:speed:script-binding hikari_speed/open-menu', 'es'),
		'command:speed:script-binding hikari_speed/open-menu?Velo cidad')
end)

test('controls in effect: script-opts first, then uosc.conf read as mp.options reads it', function()
	local conf = os.tmpname()
	write(conf, '# controls=commented\r\ncontrols=first\r\n controls=not-a-key\ncontrols=last\r\nother=x\n')
	local l = load({}, conf)
	eq(l.conf_controls(), 'last', 'last one wins, CRLF and comments')
	eq(l.current_controls(), 'last')
	mock.script_opts['uosc-controls'] = 'from-opts'
	eq(l.current_controls(), 'from-opts', 'script-opts first')
	l = load({}, false)
	eq(l.current_controls(), nil, 'no uosc.conf: uosc default, nothing of hikari')
	write(conf, 'controls=' .. string.rep('x', 9000) .. '\n')
	l = load({}, conf)
	eq(l.current_controls(), nil, 'absurdly long: left alone')
	os.remove(conf)
end)

test('start-up: tooltips set only when they change', function()
	load({['hikari-language'] = 'en'})
	eq(#appended('uosc-controls'), 0, 'English with the shipped uosc.conf: nothing to do')
	load({['hikari-language'] = 'es'})
	local list = appended('uosc-controls')
	eq(#list, 1, 'Spanish: set once')
	assert(list[1]:find('?Paletas', 1, true), 'translated')
	load({['hikari-language'] = 'es'}, false)
	eq(#appended('uosc-controls'), 0, 'no uosc.conf')
end)

test('picking a language: option, file, OSD in the new language; everything follows', function()
	local path = os.tmpname()
	local l = load({['hikari-language'] = 'es', ['uosc-languages'] = 'es,en'})
	mock.expand['~~/hikari-language.conf'] = path
	mock.props['user-data/uosc/menu/type'] = 'hikari-language'
	mock.commands = {}
	l.select_language('fr')
	eq(appended('hikari-language')[1], 'fr', 'option set at once')
	eq(read(path), l.persist_content('fr'), 'saved')
	eq(mock.osd[#mock.osd], 'Redémarrez mpv pour traduire aussi les menus d’uosc', 'restart notice, in French')
	-- mpv then notifies every script of the option.
	mock.set_script_opt('hikari-language', 'fr')
	assert(appended('uosc-controls')[1]:find('?Palettes', 1, true), 'tooltips in French')
	local updates = sent('update-menu')
	eq(#updates, 1, 'open language menu redrawn')
	assert(updates[1]:find('"title":"Langue"', 1, true), 'in French')
	os.remove(path)
	mock.expand['~~/hikari-language.conf'] = nil
end)

test('picking the language uosc started with: no restart notice; same language: saved anyway', function()
	local path = os.tmpname()
	local l = load({['hikari-language'] = 'es', ['uosc-languages'] = 'es,en'})
	mock.expand['~~/hikari-language.conf'] = path
	mock.commands = {}
	l.select_language('es')
	eq(#appended('hikari-language'), 0, 'already the language')
	eq(read(path), l.persist_content('es'), 'saved')
	eq(#mock.osd, 0, 'no notice')
	l = load({}) -- no choice yet: uosc followed the subtitle language
	mock.expand['~~/hikari-language.conf'] = path
	l.select_language(l.i18n.language())
	eq(#mock.osd, 1, 'first choice: uosc may be in another language')
	os.remove(path)
	mock.expand['~~/hikari-language.conf'] = nil
end)

