-- Run from the repository root: lua tests/test_language.lua
package.path = './tests/?.lua;' .. package.path
local mock = require('mock_mp')

local SCRIPT = 'portable_config/scripts/hikari-language.lua'
local SCRIPT_NAME = 'hikari_language'
local UOSC_CONF = 'portable_config/script-opts/uosc.conf'
local CODES = {'en', 'es', 'de', 'fr', 'it', 'pl', 'pt', 'ro', 'ru', 'tr', 'uk', 'zh-HK', 'zh-hans'}

local passed, failed = 0, 0
local function test(name, fn)
	local ok, err = pcall(fn)
	if ok then
		passed = passed + 1
		print('ok   ' .. name)
	else
		failed = failed + 1
		print('FAIL ' .. name .. '\n     ' .. tostring(err))
	end
end

local function eq(actual, expected, what)
	if actual ~= expected then
		error((what or 'value') .. ': expected ' .. tostring(expected) .. ', got ' .. tostring(actual), 2)
	end
end

local function read(path)
	local f = assert(io.open(path, 'rb'))
	local s = f:read('*a')
	f:close()
	return s
end

local function write(path, text)
	local f = assert(io.open(path, 'wb'))
	f:write(text)
	f:close()
end

-- Loads the script with `opts` as script-opts and `uosc_conf` (a path, or
-- false for none) as script-opts/uosc.conf; the shipped one by default.
local function load(opts, uosc_conf)
	mock.install(SCRIPT_NAME)
	mock.script_opts = opts or {}
	if uosc_conf ~= false then mock.config_files['script-opts/uosc.conf'] = uosc_conf or UOSC_CONF end
	HIKARI_LANGUAGE_TEST = true
	local chunk = assert(loadfile(SCRIPT))
	return chunk()
end

-- The change-list commands sent for `key` (script-opts append key=...), as values.
local function appended(key)
	local list = {}
	for _, cmd in ipairs(mock.commands) do
		if cmd[1] == 'change-list' and cmd[2] == 'script-opts' and cmd[3] == 'append' then
			local k, v = cmd[4]:match('^([^=]+)=(.*)$')
			if k == key then list[#list + 1] = v end
		end
	end
	return list
end

local function sent(message)
	local list = {}
	for _, cmd in ipairs(mock.commands) do
		if cmd[1] == 'script-message-to' and cmd[2] == 'uosc' and cmd[3] == message then list[#list + 1] = cmd[4] end
	end
	return list
end

-- The controls of the shipped uosc.conf, as uosc reads them.
local function shipped_controls()
	local value
	for line in read(UOSC_CONF):gmatch('[^\n]+') do
		if line:sub(1, 1) ~= '#' and line:match('^controls=') then value = line:sub(10) end
	end
	return value
end

test('uosc languages: the code then English; zh-HK by path too', function()
	local l = load()
	eq(l.uosc_languages('en'), 'en')
	eq(l.uosc_languages('es'), 'es,en')
	eq(l.uosc_languages('zh-hans'), 'zh-hans,en')
	eq(l.uosc_languages('zh-HK'), '~~/scripts/uosc/intl/zh-HK.json,zh-HK,en')
	eq(l.uosc_language_of('es,en'), 'es')
	eq(l.uosc_language_of('~~/scripts/uosc/intl/zh-HK.json,zh-HK,en'), 'zh-HK')
	eq(l.uosc_language_of('slang,en'), nil, 'uosc default: not one of ours')
	eq(l.uosc_language_of(nil), nil)
end)

test('saved file: both options, for every language; nothing for unknown codes', function()
	local l = load()
	eq(l.persist_content('es'), '# Generated by hikari-language.lua. Language: es\n'
		.. 'script-opts-append=hikari-language=es\nscript-opts-append=uosc-languages=es,en\n')
	for _, code in ipairs(CODES) do
		local text = l.persist_content(code)
		assert(text and text:find('hikari-language=' .. code .. '\n', 1, true), code)
		eq(select(2, text:gsub('\n', '')), 3, code .. ': three lines')
	end
	for _, bad in ipairs({'xx', 'es\nscript-opts-append=uosc-x=1', 'ES', '', 'auto'}) do eq(l.persist_content(bad), nil, bad) end
end)

test('the shipped hikari-language.conf picks no language (the system one, until a choice)', function()
	local text = read('portable_config/hikari-language.conf')
